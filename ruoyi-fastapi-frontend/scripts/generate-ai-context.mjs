import Ajv2020 from 'ajv/dist/2020.js';
import { createHash } from 'node:crypto';
import { realpathSync } from 'node:fs';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { transpileModule, ModuleKind, ScriptTarget } from 'typescript';

// Reuse the installed TypeScript compiler for the pure metadata module on the CI Node 20 runtime.
const metadataURL = new URL('../src/ai-context/definitions.ts', import.meta.url);
const compiled = transpileModule(await readFile(metadataURL, 'utf8'), {
  compilerOptions: { module: ModuleKind.ESNext, target: ScriptTarget.ES2022 },
});
const { aiContextDefinitions } = await import(
  'data:text/javascript;base64,' + Buffer.from(compiled.outputText).toString('base64')
);

const validateManifest = new Ajv2020({ strict: false }).compile(
  JSON.parse(
    await readFile(new URL('../../shared/ai-context/manifest.schema.json', import.meta.url), 'utf8')
  )
);

export function generateManifest(definitions = aiContextDefinitions) {
  const scopes = Object.fromEntries(
    Object.values(definitions)
      .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
      .map(({ id, permissions, purposes, items }) => [
        id,
        {
          permissions: {
            mode: permissions.mode,
            values: [...permissions.values],
          },
          purposes: Object.fromEntries(
            Object.entries(purposes)
              .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
              .map(([key, value]) => [
                key,
                {
                  label: value.label,
                  defaultContextIds: [...value.defaultContextIds],
                  selectableContextIds: [...value.selectableContextIds],
                },
              ])
          ),
          items: items.filter((item) => item.sensitivity !== 'secret').map((item) => ({ ...item })),
        },
      ])
  );
  const manifest = { version: 'ai-context/v1', scopes };
  if (Object.keys(scopes).length !== Object.keys(definitions).length || !validateManifest(manifest))
    throw new Error('Invalid AI manifest metadata');
  for (const scope of Object.values(scopes)) {
    const ids = new Set(scope.items.map((item) => item.id));
    if (ids.size !== scope.items.length) throw new Error('Duplicate AI context item');
    for (const purpose of Object.values(scope.purposes)) {
      const refs = [...purpose.defaultContextIds, ...purpose.selectableContextIds];
      if (new Set(refs).size !== refs.length || refs.some((id) => !ids.has(id)))
        throw new Error('Invalid AI context purpose reference');
    }
  }
  return JSON.stringify(manifest, null, 2) + '\n';
}

if (process.argv[1] && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  const expected = generateManifest();
  const revision = createHash('sha256').update(expected).digest('hex');
  const outputs = [
    ['../../shared/ai-context/manifest.json', expected],
    ['../../ruoyi-fastapi-backend/resources/ai-context/manifest.json', expected],
    [
      '../src/ai-context/manifest-revision.ts',
      `// Generated by scripts/generate-ai-context.mjs.\nexport const manifestRevision = '${revision}';\n`,
    ],
  ];
  for (const [path, content] of outputs) {
    const target = new URL(path, import.meta.url);
    if (process.argv.includes('--check')) {
      if ((await readFile(target, 'utf8')) !== content)
        throw new Error('AI manifest drift: ' + target.pathname);
    } else {
      await mkdir(new URL('.', target), { recursive: true });
      await writeFile(target, content);
    }
  }
}
