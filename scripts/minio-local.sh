#!/usr/bin/env bash
# Non-production MinIO fixture for local file-asset development and integration tests.
#
# - Independent container/volume/bucket/credentials; never reuses steamer-plane's 9000/9090 MinIO.
# - Image pinned by digest. It is a TEST fixture only and does NOT decide the production
#   distribution (TBD-PROD-01 stays open).
# - Writes untracked ruoyi-fastapi-backend/.env.dev.local (ignored by git) with generated credentials.
#
# Usage: ./scripts/minio-local.sh [up|status|down]   (down keeps the volume)
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BACKEND_DIR="$ROOT_DIR/ruoyi-fastapi-backend"
ENV_LOCAL="$BACKEND_DIR/.env.dev.local"
CONTAINER=ruoyi-minio-local
VOLUME=ruoyi-minio-local-data
# minio/minio RELEASE.2025-09-07T16-13-09Z (multi-arch manifest digest)
IMAGE="minio/minio@sha256:14cea493d9a34af32f524e538b8346cf79f3321eff8e708c1e2960462bd8936e"
S3_PORT=19000
CONSOLE_PORT=19001
BUCKET="${FILE_ASSET_S3_BUCKET:-ruoyi-file-assets-dev}"
POLICY_NAME=ruoyi-file-assets-app

random_secret() { openssl rand -hex "$(( (${1:-32} + 1) / 2 ))" | cut -c1-"${1:-32}"; }

read_local() { [ -f "$ENV_LOCAL" ] && grep -E "^$1=" "$ENV_LOCAL" | tail -1 | cut -d= -f2- | tr -d "'\"" || true; }

port_busy() { lsof -nP -iTCP:"$1" -sTCP:LISTEN >/dev/null 2>&1; }

cmd_status() {
  docker ps -a --filter "name=^${CONTAINER}$" --format '{{.Names}} {{.Status}} {{.Ports}}'
  curl -fsS "http://127.0.0.1:${S3_PORT}/minio/health/live" >/dev/null && echo "S3 endpoint healthy on 127.0.0.1:${S3_PORT}" || echo "S3 endpoint not reachable"
}

cmd_down() {
  docker rm -f "$CONTAINER" >/dev/null 2>&1 || true
  echo "removed container $CONTAINER (volume $VOLUME kept)"
}

cmd_up() {
  local root_user root_password app_key app_secret installation_id
  root_user="$(read_local FILE_ASSET_S3_ADMIN_ACCESS_KEY)"; root_user="${root_user:-ruoyi-minio-root}"
  root_password="$(read_local FILE_ASSET_S3_ADMIN_SECRET_KEY)"; root_password="${root_password:-$(random_secret 40)}"
  app_key="$(read_local FILE_ASSET_S3_ACCESS_KEY)"; app_key="${app_key:-ruoyi-app-$(random_secret 8 | tr 'A-Z' 'a-z')}"
  app_secret="$(read_local FILE_ASSET_S3_SECRET_KEY)"; app_secret="${app_secret:-$(random_secret 40)}"
  installation_id="$(read_local FILE_ASSET_INSTALLATION_ID)"; installation_id="${installation_id:-ruoyi-dev-$(hostname -s | tr -cd 'A-Za-z0-9-')-$(random_secret 6 | tr 'A-Z' 'a-z')}"

  if ! docker ps --format '{{.Names}}' | grep -qx "$CONTAINER"; then
    if docker ps -a --format '{{.Names}}' | grep -qx "$CONTAINER"; then
      docker start "$CONTAINER" >/dev/null
    else
      for port in "$S3_PORT" "$CONSOLE_PORT"; do
        if port_busy "$port"; then echo "port $port is already in use; refusing to start" >&2; exit 1; fi
      done
      docker run -d --name "$CONTAINER" --restart unless-stopped \
        -p "127.0.0.1:${S3_PORT}:9000" -p "127.0.0.1:${CONSOLE_PORT}:9001" \
        -v "$VOLUME:/data" \
        -e MINIO_ROOT_USER="$root_user" -e MINIO_ROOT_PASSWORD="$root_password" \
        "$IMAGE" server /data --console-address :9001 >/dev/null
    fi
  fi
  for _ in $(seq 1 30); do
    curl -fsS "http://127.0.0.1:${S3_PORT}/minio/health/live" >/dev/null 2>&1 && break
    sleep 1
  done

  umask 077
  cat >"$ENV_LOCAL" <<EOF
# Generated by scripts/minio-local.sh — local non-production values, never commit.
FILE_ASSET_S3_ENDPOINT='http://127.0.0.1:${S3_PORT}'
FILE_ASSET_S3_BUCKET='${BUCKET}'
FILE_ASSET_S3_REGION='us-east-1'
FILE_ASSET_S3_ADDRESSING_STYLE='path'
FILE_ASSET_S3_ACCESS_KEY='${app_key}'
FILE_ASSET_S3_SECRET_KEY='${app_secret}'
FILE_ASSET_INSTALLATION_ID='${installation_id}'
# Bootstrap-only admin credentials (CLI); the web process never reads these.
FILE_ASSET_S3_ADMIN_ACCESS_KEY='${root_user}'
FILE_ASSET_S3_ADMIN_SECRET_KEY='${root_password}'
EOF

  local policy_file
  policy_file="$(mktemp)"
  (cd "$BACKEND_DIR" && FILE_ASSET_S3_BUCKET="$BUCKET" ./venv/bin/python scripts/file_assets.py --env dev print-app-policy) >"$policy_file"
  docker cp "$policy_file" "$CONTAINER:/tmp/${POLICY_NAME}.json" >/dev/null
  rm -f "$policy_file"
  docker exec "$CONTAINER" sh -c "
    mc alias set local http://127.0.0.1:9000 '$root_user' '$root_password' >/dev/null &&
    (mc admin policy create local $POLICY_NAME /tmp/${POLICY_NAME}.json >/dev/null 2>&1 || true) &&
    (mc admin user add local '$app_key' '$app_secret' >/dev/null 2>&1 || true) &&
    (mc admin policy attach local $POLICY_NAME --user '$app_key' >/dev/null 2>&1 || true)
  "
  (cd "$BACKEND_DIR" && set -a && . ./.env.dev.local && set +a && \
    ./venv/bin/python scripts/file_assets.py --env dev bootstrap-storage && \
    ./venv/bin/python scripts/file_assets.py --env dev check-storage --write-probe)
  echo "MinIO fixture ready: S3 http://127.0.0.1:${S3_PORT}, console http://127.0.0.1:${CONSOLE_PORT}, bucket ${BUCKET}"
}

case "${1:-up}" in
  up) cmd_up ;;
  status) cmd_status ;;
  down) cmd_down ;;
  *) echo "usage: $0 [up|status|down]" >&2; exit 2 ;;
esac
