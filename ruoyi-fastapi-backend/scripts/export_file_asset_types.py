#!/usr/bin/env python3
"""Export the backend file type registry for frontend accept/hints (single declaration, generated artifact)."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

BACKEND_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = (
    BACKEND_ROOT.parent / 'ruoyi-fastapi-frontend' / 'src' / 'utils' / 'file-assets' / 'types.generated.json'
)
if str(BACKEND_ROOT) not in sys.path:
    sys.path.insert(0, str(BACKEND_ROOT))


def render() -> str:
    from modules.file_assets.domain.types import (
        FILE_TYPES,
        IMAGE_TYPE_IDS,
        MAX_ATTACHMENT_BYTES,
        MAX_IMAGE_BYTES,
        OFFICE_BASELINE_TYPE_IDS,
    )

    payload = {
        '$comment': 'Generated by ruoyi-fastapi-backend/scripts/export_file_asset_types.py; do not edit.',
        'types': {
            type_id: {
                'extensions': list(spec.extensions),
                'mediaType': spec.media_type,
                'family': spec.family.value,
            }
            for type_id, spec in FILE_TYPES.items()
        },
        'imageTypeIds': list(IMAGE_TYPE_IDS),
        'officeBaselineTypeIds': list(OFFICE_BASELINE_TYPE_IDS),
        'maxImageBytes': MAX_IMAGE_BYTES,
        'maxAttachmentBytes': MAX_ATTACHMENT_BYTES,
    }
    return json.dumps(payload, ensure_ascii=False, indent=2) + '\n'


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument('--check', action='store_true', help='fail when the committed artifact drifted')
    args = parser.parse_args(argv)
    content = render()
    if args.check:
        current = args.output.read_text(encoding='utf-8') if args.output.exists() else ''
        if current != content:
            print(f'file asset type registry drifted: regenerate {args.output}', file=sys.stderr)
            return 1
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content, encoding='utf-8')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
